package com.sabihon.todo

import android.app.Application
import android.content.Context
import android.content.pm.ApplicationInfo
import androidx.hilt.work.HiltWorkerFactory
import androidx.work.Configuration
import com.google.firebase.appcheck.FirebaseAppCheck
import com.google.firebase.appcheck.debug.DebugAppCheckProviderFactory
import com.google.firebase.appcheck.playintegrity.PlayIntegrityAppCheckProviderFactory
import com.sabihon.todo.notifications.AppForegroundTracker
import com.sabihon.todo.notifications.NotificationHelper
import dagger.hilt.android.HiltAndroidApp
import java.io.File
import javax.inject.Inject

/**
 * Application class for daymark . – entry point for Hilt DI.
 * Implements WorkManager Configuration.Provider for Hilt workers.
 */
@HiltAndroidApp
class SabihonApp : Application(), Configuration.Provider {

    @Inject
    lateinit var workerFactory: HiltWorkerFactory

    @Inject
    lateinit var notificationHelper: NotificationHelper

    @Inject
    lateinit var foregroundTracker: AppForegroundTracker

    override val workManagerConfiguration: Configuration
        get() = Configuration.Builder()
            .setWorkerFactory(workerFactory)
            .build()

    override fun onCreate() {
        super.onCreate()
        installAppCheck()

        // "Is a screen visible?" decides whether a due reminder becomes an in-app popup or a
        // system notification, so it has to be tracked from the first activity onwards.
        try {
            foregroundTracker.attach(this)
        } catch (e: Exception) {
            android.util.Log.e("SabihonApp", "Foreground tracking unavailable", e)
        }

        // All three reminder channels, early: posting to a missing channel throws on O+.
        try {
            notificationHelper.ensureChannels()
        } catch (e: Exception) {
            android.util.Log.e("SabihonApp", "Failed to create notification channels", e)
        }
    }

    /**
     * Installs Firebase App Check before any `firebase-ai` call.
     *
     * Firebase AI Logic enforces App Check (`Registered (Enforced)`): release builds
     * attest with Play Integrity, while debug builds use `DebugAppCheckProviderFactory`
     * and eagerly request a token at launch so the persistent debug secret UUID is
     * immediately available in `Settings > AI` (one tap to copy) as well as Logcat.
     */
    private fun installAppCheck() {
        try {
            val debuggable = (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0
            val appCheck = FirebaseAppCheck.getInstance()
            val factory = if (debuggable) {
                DebugAppCheckProviderFactory.getInstance()
            } else {
                PlayIntegrityAppCheckProviderFactory.getInstance()
            }
            appCheck.installAppCheckProviderFactory(factory)
            if (debuggable) {
                // Trigger secret generation immediately so Settings > AI can copy it
                // before the user even taps a Gemini action.
                appCheck.getAppCheckToken(false)
            }
        } catch (e: Exception) {
            android.util.Log.e("SabihonApp", "App Check not installed", e)
        }
    }

    companion object {
        private const val DEBUG_STORE_PREFIX = "com.google.firebase.appcheck.debug.store"
        private const val DEBUG_SECRET_KEY = "com.google.firebase.appcheck.debug.DEBUG_SECRET"

        /**
         * Returns the Firebase `project_id` compiled into the APK from `google-services.json`.
         */
        fun firebaseProjectId(context: Context): String? = runCatching {
            val resId = context.resources.getIdentifier("project_id", "string", context.packageName)
            if (resId != 0) context.getString(resId).takeIf { it.isNotBlank() } else null
        }.getOrNull()

        /**
         * Reads the persistent App Check debug secret UUID generated by
         * `DebugAppCheckProviderFactory` from the app's `shared_prefs` directory.
         */
        fun readAppCheckDebugToken(context: Context): String? = runCatching {
            val debuggable = (context.applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE) != 0
            if (!debuggable) return@runCatching null
            val prefsDir = File(context.applicationInfo.dataDir, "shared_prefs")
            val storeFiles = prefsDir.listFiles()?.filter { file ->
                file.name.startsWith(DEBUG_STORE_PREFIX) && file.name.endsWith(".xml")
            }.orEmpty()
            for (file in storeFiles) {
                val prefName = file.name.removeSuffix(".xml")
                val prefs = context.getSharedPreferences(prefName, Context.MODE_PRIVATE)
                val secret = prefs.getString(DEBUG_SECRET_KEY, null)?.trim()
                if (!secret.isNullOrEmpty()) return@runCatching secret
            }
            // Kick token generation once more if the background task hasn't flushed yet.
            FirebaseAppCheck.getInstance().getAppCheckToken(false)
            null
        }.getOrNull()
    }
}
